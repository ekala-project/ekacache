// Command goerrno prints jigd's Go errno string table (crates/jigd/src/goerr_table.rs).
//
// Go's syscall error strings differ from glibc strerror in case and wording, and jigd's log
// lines embed them (implementation/03-jigd-server.md §Logging and error text). Regenerate with
//
//	go run ./crates/jigd/gen/goerrno/main.go > crates/jigd/src/goerr_table.rs
//
// on linux/amd64 with the Go toolchain the legacy daemon was built with (go1.25).
package main

import (
	"fmt"
	"runtime"
	"syscall"
)

func main() {
	fmt.Printf("//! Go's `syscall.Errno` strings on %s/%s (%s), generated by `crates/jigd/gen/goerrno`.\n", runtime.GOOS, runtime.GOARCH, runtime.Version())
	fmt.Println("//! Do not edit by hand. An errno outside the table prints as `errno <n>` (Go's fallback).")
	fmt.Println()
	fmt.Println("/// Indexed by errno value; an empty string means \"no entry\".")
	fmt.Println("pub(crate) static ERRNO: &[&str] = &[")
	for i := 0; i < 134; i++ {
		s := syscall.Errno(i).Error()
		if s == fmt.Sprintf("errno %d", i) {
			s = ""
		}
		fmt.Printf("    %q, // %d\n", s, i)
	}
	fmt.Println("];")
}
