#!/bin/sh
# Prints jigd's Go errno string table for macOS (crates/jigd/src/goerr_table_darwin.rs).
#
# main.go prints the table of the host it runs on, and Go cannot run a darwin binary here, so
# this reads the table straight from Go's source: `var errors` in
# $GOROOT/src/syscall/zerrors_darwin_arm64.go, the same strings `syscall.Errno.Error()` returns.
# darwin/amd64 has the same table without 106 (goerr.rs handles that). Regenerate with
#
#	sh crates/jigd/gen/goerrno/darwin.sh > crates/jigd/src/goerr_table_darwin.rs
#
# using the Go toolchain the legacy daemon was built with (go1.25).
set -eu
goroot=$(go env GOROOT)
src="$goroot/src/syscall/zerrors_darwin_arm64.go"
echo "//! Go's \`syscall.Errno\` strings on darwin/arm64 ($(go env GOVERSION)), generated by"
echo "//! \`crates/jigd/gen/goerrno/darwin.sh\`. Do not edit by hand. An errno outside the table prints"
echo "//! as \`errno <n>\` (Go's fallback)."
echo
echo '/// Indexed by errno value; an empty string means "no entry".'
echo 'pub(crate) static ERRNO: &[&str] = &['
sed -n '/^var errors = \[\.\.\.\]string{/,/^}/p' "$src" |
  sed -nE 's/^[[:space:]]*([0-9]+):[[:space:]]*(".*"),$/\1 \2/p' |
  awk '
    { n = $1; $1 = ""; sub(/^ /, ""); s[n] = $0; if (n > max) max = n }
    END {
      for (i = 0; i <= max; i++) {
        v = (i in s) ? s[i] : "\"\""
        printf "    %-52s // %d\n", v ",", i
      }
    }'
echo '];'
